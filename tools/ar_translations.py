def fill_french():
    """Fill the French catalogue with the French source strings.

    The French strings are the source language of the templates, so the
    ``msgid`` of every entry already *is* the French text. Copying it
    into the ``msgstr`` keeps the French catalogue complete and
    explicit, and stops a later ``makemessages`` run from silently
    emptying it.
    """
    catalog = polib.pofile(str(FR_PO_PATH))

    written = 0
    for entry in catalog:
        if entry.msgid_plural:
            if not entry.msgstr_plural:
                entry.msgstr_plural = {0: entry.msgid, 1: entry.msgid_plural}
                written += 1
            continue
        if not entry.msgstr:
            entry.msgstr = entry.msgid
            written += 1

    catalog.save(str(FR_PO_PATH))
    catalog.save_as_mofile(str(FR_MO_PATH))
    return written


def main():
    """Write the translations into the Arabic catalogue and compile it."""
    french_written = fill_french()
    print(
        f"{french_written} translation(s) written in "
        f"{FR_PO_PATH.relative_to(BASE_DIR)}"
    )

    catalog = polib.pofile(str(PO_PATH))

    written = 0
    missing = []
    for entry in catalog:
        if entry.msgid_plural:
            forms = PLURALS.get(entry.msgid)
            if not forms:
                missing.append(entry.msgid)
                continue
            entry.msgstr_plural = {
                str(index): form for index, form in enumerate(forms)
            }
            written += 1
            continue

        translation = TRANSLATIONS.get(entry.msgid)
        if translation is None:
            missing.append(entry.msgid)
            continue
        entry.msgstr = translation
        written += 1

    catalog.save(str(PO_PATH))
    catalog.save_as_mofile(str(MO_PATH))

    print(f"{written} translation(s) written in {PO_PATH.relative_to(BASE_DIR)}")
    if missing:
        print(f"{len(missing)} string(s) still untranslated:", file=sys.stderr)
        for msgid in missing:
            print(f"  - {msgid}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
